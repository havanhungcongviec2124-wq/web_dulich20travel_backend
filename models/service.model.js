const mongoose = require("mongoose");

const serviceSchema = new mongoose.Schema(
  {
    code: { type: String, trim: true, index: true },
    slug: { type: String, required: true, unique: true, trim: true },
    name: { type: String, required: true, trim: true },
    subtitle: { type: String, default: "" },
    category: { type: String, required: true, index: true },
    categoryName: { type: String, default: "" },
    locationSlug: { type: String, default: "", index: true },
    locationName: { type: String, default: "" },
    region: { type: String, default: "" },
    address: { type: String, default: "" },
    duration: { type: String, default: "" },
    departure: { type: String, default: "" },
    price: { type: Number, default: 0 },
    weekendPrice: { type: Number },
    holidayPrice: { type: Number },
    fixedPrices: { type: Boolean, default: false },
    priceUnit: { type: String, default: "khách" },
    marketPrice: { type: Number, default: 0 },
    rating: { type: Number, default: 4.8 },
    reviews: { type: Number, default: 0 },
    stars: { type: Number, default: 0 },
    image: { type: String, default: "" },
    secondaryImage: { type: String, default: "" },
    gallery: { type: [String], default: [] },
    badge: { type: String, default: "" },
    tag: { type: String, default: "" },
    featuredBadge: { type: String, default: "" },
    tags: { type: [String], default: [] },
    amenities: { type: [mongoose.Schema.Types.Mixed], default: [] },
    amenitiesDetail: { type: [String], default: [] },
    highlights: { type: [String], default: [] },
    included: { type: [String], default: [] },
    excluded: { type: [String], default: [] },
    notes: { type: [String], default: [] },
    options: { type: [mongoose.Schema.Types.Mixed], default: [] },
    itinerary: { type: [mongoose.Schema.Types.Mixed], default: [] },
    summary: { type: String, default: "" },
    overviewTitle: { type: String, default: "" },
    summaryMobile: { type: String, default: "" },
    intro: { type: String, default: "" },
    description: { type: String, default: "" },
    roomType: { type: String, default: "" },
    guestStandard: { type: String, default: "" },
    featured: { type: Boolean, default: false },
    status: { type: String, default: "Hiển thị" },
    published: { type: Boolean, default: true },
    consultant: { type: String, default: "" },
    updatedAtLabel: { type: String, default: "" },
    displayPrice: { type: Number },
  },
  { timestamps: true }
);

module.exports = mongoose.model("Service", serviceSchema);
